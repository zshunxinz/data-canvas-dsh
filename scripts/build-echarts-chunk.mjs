/**
 * Build step (offline, no bundler): wrap the ECharts UMD build into a
 * ModuleLoader chunk for the plugin's client half.
 *
 * Why: the host's client `require` only resolves the module table (platform
 * seeds + registered package factories). Plugin npm dependencies are NOT in
 * that table, so `require('echarts')` inside client.js cannot work — measured,
 * not assumed (see docs 画布能力对齐规划 §三). The supported escape hatch is a
 * package-local chunk: a `client.*.js` file shipped in the tarball, loaded via
 * `require.async('./client.echarts.js')`.
 *
 * The UMD build detects `module.exports` and assigns into it, so executing it
 * inside a function whose scope defines `module`/`exports` captures the API.
 *
 * Run after `pnpm install` / whenever echarts updates:
 *   node scripts/build-echarts-chunk.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const here = dirname(fileURLToPath(import.meta.url))
const pluginRoot = join(here, '..')

// Resolve echarts from the plugin's own dependencies.
const requireFromPlugin = createRequire(join(pluginRoot, 'package.json'))
const echartsPkgPath = requireFromPlugin.resolve('echarts/package.json')
const echartsRoot = dirname(echartsPkgPath)
const echartsVersion = requireFromPlugin('echarts/package.json').version

const umd = readFileSync(join(echartsRoot, 'dist', 'echarts.common.min.js'), 'utf8')

// The chunk is a ModuleLoader package factory: `require.async('./client.echarts.js')`
// resolves to this file's exports. Execute the UMD inside a scope where
// `module`/`exports` exist so its CommonJS detection picks them up.
const chunk = `/**
 * client.echarts.js — echarts ${echartsVersion} (common build) wrapped as a
 * package-local ModuleLoader chunk for data-canvas-dsh.
 *
 * GENERATED by scripts/build-echarts-chunk.mjs from
 * echarts@${echartsVersion} dist/echarts.common.min.js — do not edit.
 * Apache-2.0 © The Apache Software Foundation (echarts is distributed as-is).
 */
window.__ModuleLoader__.load({
  id: 'data-canvas-dsh/client.echarts.js',
  factory: () => {
    // Strategy: let the UMD take its GLOBAL branch and read window.echarts.
    //
    // The CJS branch (typeof exports === 'object' && typeof module) was tried
    // first with var-shadowed bindings — it passed in Node, but inside the
    // ModuleLoader's factory wrapper the bindings did not take (measured: the
    // API landed on window anyway, init returned a 22-key fragment without
    // setOption/get, and every setOption threw). The global branch is what the
    // wrapper reliably reaches in the real client, and it installs the full
    // API: window.echarts.init / use / graphic …
    ;
${umd}
    const lib = window.echarts
    if (!lib || typeof lib.init !== 'function') {
      throw new Error('client.echarts.js: UMD did not produce an echarts API')
    }
    // Detach from window so repeated loads (HMR) do not double-register.
    try { delete window.echarts } catch { window.echarts = undefined }
    return lib
  },
})
`

const outPath = join(pluginRoot, 'client.echarts.js')
mkdirSync(dirname(outPath), { recursive: true })
writeFileSync(outPath, chunk, 'utf8')
console.log(`written: ${outPath}`)
console.log(`size: ${(Buffer.byteLength(chunk, 'utf8') / 1024).toFixed(0)}KB (echarts ${echartsVersion})`)
